const LANGS = [
  { code: "en", label: "English",  short: "EN" },
  { code: "ko", label: "한국어",   short: "KO" },
  { code: "ja", label: "日本語",   short: "JA" },
  { code: "zh", label: "中文",     short: "ZH" },
];

const I18nContext = React.createContext({ lang: "en", t: (k) => k, setLang: () => {} });

const I18nProvider = ({ children }) => {
  const [lang, setLangState] = React.useState(() => {
    try {
      // 1. Check ?lang= in URL (matches hreflang)
      const url = new URL(window.location.href);
      const urlLang = url.searchParams.get("lang");
      if (urlLang && TRANSLATIONS[urlLang]) return urlLang;
      // 2. Check localStorage
      const saved = localStorage.getItem("ow_lang");
      if (saved && TRANSLATIONS[saved]) return saved;
      // 3. Check browser language
      const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
      if (TRANSLATIONS[nav]) return nav;
    } catch (e) {}
    return "en";
  });
  const setLang = (l) => {
    setLangState(l);
    try { localStorage.setItem("ow_lang", l); } catch (e) {}
    try { document.documentElement.lang = l; } catch (e) {}
  };
  React.useEffect(() => { try { document.documentElement.lang = lang; } catch (e) {} }, [lang]);
  const t = React.useCallback((key) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] ?? TRANSLATIONS.en[key] ?? key;
  }, [lang]);
  return (
    <I18nContext.Provider value={{ lang, setLang, t, langs: LANGS }}>
      {children}
    </I18nContext.Provider>
  );
};

const useI18n = () => React.useContext(I18nContext);

window.I18nContext = I18nContext;
window.I18nProvider = I18nProvider;
window.useI18n = useI18n;
window.LANGS = LANGS;
